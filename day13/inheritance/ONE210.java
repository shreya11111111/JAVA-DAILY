package day13.inheritance;

public class ONE210 {
  public static void main(String[] args){
    int start = 1;
    int end = 10;
    while(start<=end){
      start = start + 1;
      System.out.println();
    }
    QUE1();
  }
  public static void QUE1(){
    int i = 1;
    int j = 10;
    while(i<=j){
      System.out.println(i);
      i = i+1;
    }
  }
  
}
